/* Round Constants */
static const uint32_t rcon[10] = {
    0x01000000, 0x02000000, 0x04000000, 0x08000000, 0x10000000,
    0x20000000, 0x40000000, 0x80000000, 0x1b000000, 0x36000000
};

static uint32_t sub_word(uint32_t w)
{
    return ((uint32_t)sbox[(w >> 24) & 0xff] << 24) |
           ((uint32_t)sbox[(w >> 16) & 0xff] << 16) |
           ((uint32_t)sbox[(w >>  8) & 0xff] <<  8) |
           ((uint32_t)sbox[ w        & 0xff]);
}

static uint32_t rot_word(uint32_t w)
{
    return (w << 8) | (w >> 24);
}

void aes128_key_expansion(struct aes128_ctx *ctx, const uint8_t *key)
{
    for (int i = 0; i < 4; i++) {
        ctx->round_keys[i] = ((uint32_t)key[4 * i] << 24) |
                             ((uint32_t)key[4 * i + 1] << 16) |
                             ((uint32_t)key[4 * i + 2] << 8) |
                             ((uint32_t)key[4 * i + 3]);
    }

    for (int i = 4; i < 44; i++) {
        uint32_t temp = ctx->round_keys[i - 1];
        if (i % 4 == 0) {
            temp = sub_word(rot_word(temp)) ^ rcon[(i / 4) - 1];
        }
        ctx->round_keys[i] = ctx->round_keys[i - 4] ^ temp;
    }
}

static void add_round_key(uint8_t state[4][4], const uint32_t *rk)
{
    for (int c = 0; c < 4; c++) {
        uint32_t w = rk[c];
        state[0][c] ^= (w >> 24) & 0xff;
        state[1][c] ^= (w >> 16) & 0xff;
        state[2][c] ^= (w >>  8) & 0xff;
        state[3][c] ^=  w        & 0xff;
    }
}

static void sub_bytes(uint8_t state[4][4])
{
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            state[r][c] = sbox[state[r][c]];
}

static void inv_sub_bytes(uint8_t state[4][4])
{
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            state[r][c] = rsbox[state[r][c]];
}

static void shift_rows(uint8_t state[4][4])
{
    uint8_t t;
    /* Row 1 shift 1 */
    t = state[1][0]; state[1][0] = state[1][1]; state[1][1] = state[1][2]; state[1][2] = state[1][3]; state[1][3] = t;
    /* Row 2 shift 2 */
    t = state[2][0]; state[2][0] = state[2][2]; state[2][2] = t;
    t = state[2][1]; state[2][1] = state[2][3]; state[2][3] = t;
    /* Row 3 shift 3 */
    t = state[3][3]; state[3][3] = state[3][2]; state[3][2] = state[3][1]; state[3][1] = state[3][0]; state[3][0] = t;
}

static void inv_shift_rows(uint8_t state[4][4])
{
    uint8_t t;
    /* Row 1 shift right 1 */
    t = state[1][3]; state[1][3] = state[1][2]; state[1][2] = state[1][1]; state[1][1] = state[1][0]; state[1][0] = t;
    /* Row 2 shift right 2 */
    t = state[2][0]; state[2][0] = state[2][2]; state[2][2] = t;
    t = state[2][1]; state[2][1] = state[2][3]; state[2][3] = t;
    /* Row 3 shift right 3 */
    t = state[3][0]; state[3][0] = state[3][1]; state[3][1] = state[3][2]; state[3][2] = state[3][3]; state[3][3] = t;
}

static uint8_t xtime(uint8_t x)
{
    return ((x << 1) ^ (((x >> 7) & 1) * 0x1b));
}

static uint8_t multiply(uint8_t x, uint8_t y)
{
    return (((y & 1) * x) ^
            ((y >> 1 & 1) * xtime(x)) ^
            ((y >> 2 & 1) * xtime(xtime(x))) ^
            ((y >> 3 & 1) * xtime(xtime(xtime(x)))) ^
            ((y >> 4 & 1) * xtime(xtime(xtime(xtime(x))))));
}

static void mix_columns(uint8_t state[4][4])
{
    for (int c = 0; c < 4; c++) {
        uint8_t a = state[0][c], b = state[1][c], d = state[2][c], e = state[3][c];
        state[0][c] = xtime(a ^ b) ^ b ^ d ^ e;
        state[1][c] = xtime(b ^ d) ^ d ^ e ^ a;
        state[2][c] = xtime(d ^ e) ^ e ^ a ^ b;
        state[3][c] = xtime(e ^ a) ^ a ^ b ^ d;
    }
}

static void inv_mix_columns(uint8_t state[4][4])
{
    for (int c = 0; c < 4; c++) {
        uint8_t a = state[0][c], b = state[1][c], d = state[2][c], e = state[3][c];
        state[0][c] = multiply(a, 0x0e) ^ multiply(b, 0x0b) ^ multiply(d, 0x0d) ^ multiply(e, 0x09);
        state[1][c] = multiply(a, 0x09) ^ multiply(b, 0x0e) ^ multiply(d, 0x0b) ^ multiply(e, 0x0d);
        state[2][c] = multiply(a, 0x0d) ^ multiply(b, 0x09) ^ multiply(d, 0x0e) ^ multiply(e, 0x0b);
        state[3][c] = multiply(a, 0x0b) ^ multiply(b, 0x0d) ^ multiply(d, 0x09) ^ multiply(e, 0x0e);
    }
}

void aes128_encrypt_block(const struct aes128_ctx *ctx, const uint8_t *input, uint8_t *output)
{
    uint8_t state[4][4];
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            state[r][c] = input[r + 4 * c];

    add_round_key(state, &ctx->round_keys[0]);

    for (int round = 1; round < 10; round++) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, &ctx->round_keys[4 * round]);
    }

    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, &ctx->round_keys[40]);

    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            output[r + 4 * c] = state[r][c];
}

void aes128_decrypt_block(const struct aes128_ctx *ctx, const uint8_t *input, uint8_t *output)
{
    uint8_t state[4][4];
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            state[r][c] = input[r + 4 * c];

    add_round_key(state, &ctx->round_keys[40]);

    for (int round = 9; round >= 1; round--) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, &ctx->round_keys[4 * round]);
        inv_mix_columns(state);
    }

    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, &ctx->round_keys[0]);

    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++)
            output[r + 4 * c] = state[r][c];
}

void aes128_cbc_encrypt(const struct aes128_ctx *ctx, uint8_t *iv, const uint8_t *input, uint8_t *output, size_t length)
{
    size_t blocks = length / 16;
    uint8_t block[16];

    for (size_t b = 0; b < blocks; b++) {
        for (int i = 0; i < 16; i++) {
            block[i] = input[b * 16 + i] ^ iv[i];
        }
        aes128_encrypt_block(ctx, block, &output[b * 16]);
        for (int i = 0; i < 16; i++) {
            iv[i] = output[b * 16 + i];
        }
    }
}

void aes128_cbc_decrypt(const struct aes128_ctx *ctx, uint8_t *iv, const uint8_t *input, uint8_t *output, size_t length)
{
    size_t blocks = length / 16;
    uint8_t next_iv[16];

    for (size_t b = 0; b < blocks; b++) {
        for (int i = 0; i < 16; i++) {
            next_iv[i] = input[b * 16 + i];
        }
        aes128_decrypt_block(ctx, &input[b * 16], &output[b * 16]);
        for (int i = 0; i < 16; i++) {
            output[b * 16 + i] ^= iv[i];
            iv[i] = next_iv[i];
        }
    }
}
